export const FUNCTION_LABELS = Object.freeze(["Dano","Proteção","Controle","Utilidade","Detecção"]);

export function ritualFunctions(name) {
	if (typeof name !== "string") return [];
	const normalized = name.replace(/^Amaldiçoar Arma - (Conhecimento|Energia|Morte|Sangue)$/i, "Amaldiçoar Arma").normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toLocaleLowerCase("pt-BR");
	const key = Object.keys(RITUAL_FUNCTIONS).find((entry) => entry.normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toLocaleLowerCase("pt-BR") === normalized);
	return key ? [...RITUAL_FUNCTIONS[key]] : [];
}

export function filterRitualsByFunction(rituals, selected) {
	if (!selected) return rituals;
	return rituals.filter((ritual) => {
		const functions = ritualFunctions(ritual.name);
		return selected === "sem-funcao" ? functions.length === 0 : functions.includes(selected);
	});
}
